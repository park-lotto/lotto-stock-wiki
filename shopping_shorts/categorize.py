def category_of_hashtag(tag):
    """발굴 해시태그 → 카테고리. 매핑에 없으면 키워드 판정, 그것도 안 되면 ''."""
    t = (tag or "").strip().lstrip("#").lower()
    if not t:
        return ""
    if t in HASHTAG_CATEGORY:
        return HASHTAG_CATEGORY[t]
    guess = categorize("", t)
    return "" if guess == "기타" else guess
