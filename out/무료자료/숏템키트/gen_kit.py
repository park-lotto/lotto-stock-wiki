def clean_hooks(rows, limit):
    out, seen = [], set()
    for h, v, *rest in rows:
        for a, b in FIX.items():
            h = h.replace(a, b)
        if any(k in h for k in DROP) or len(h) > 40:
            continue
        key = re.sub(r"[^가-힣]", "", h)[:7]
        if key in seen:
            continue
        seen.add(key)
        out.append([h, v, *rest])
        if len(out) >= limit:
            break
    return out


