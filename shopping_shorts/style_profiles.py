def style_block(name=None):
    """생성 프롬프트에 얹을 스타일 블록. 모르는 이름·off면 ''(종전 동일 — 회귀 0).
    trio(후보별 배정 모드)의 공통 생성 블록은 maison — 후보별 결은 candidate_style_block(i)로
    **생성 단계에서** 입힌다(아래). 후보 인덱스를 모르는 호출자는 여기로 남는다."""
    name = name if name is not None else active_style()
    if name == "trio":
        name = "maison"
