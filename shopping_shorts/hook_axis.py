UNKNOWN = ""            # 판정 실패 — 호출부는 기존 동작으로 폴백해야 한다


def head_text(script):
    """전사({segments, full_text})에서 판정에 쓸 **앞 2컷**을 뽑는다.

    ★2컷인 이유: 첫 컷만 쓰면 커버리지가 73%→56%로 떨어진다(실측 527편).
      인스타 전사는 자막 단위라 첫 컷이 문장 중간에서 끊긴다.
    """
    if not isinstance(script, dict):
        return ""
    segs = [s for s in (script.get("segments") or [])
            if isinstance(s, dict) and (s.get("text") or "").strip()]
    if segs:
        return " ".join(s["text"].strip() for s in segs[:2])
    return (script.get("full_text") or "")[:80]


def axis_of(script_or_text):
    """전사(dict) 또는 훅 문자열 → 축 이름. 못 가르면 ""(UNKNOWN).

    ★한국어 대본만 판정한다 — 중국어(샤오홍슈) 편은 문형이 달라 별도 축이 필요하다.
    """
    head = script_or_text if isinstance(script_or_text, str) else head_text(script_or_text)
    if not head or not re.search(r"[가-힣]", head):
        return UNKNOWN
    for name, rx, _n, _ch in AXES:
        if re.search(rx, head):
            return name
    return UNKNOWN


def spine_name_for(script_or_text):
    """전사 → 이 영상에 맞는 스파인 **이름**. 매핑이 없으면 ""."""
    return AXIS_TO_SPINE.get(axis_of(script_or_text), "")


def axis_evidence(axis):
    """그 축이 몇 편/몇 채널 실측에서 나왔나 — 화면이 근거를 말할 수 있게."""
    for name, _rx, n, ch in AXES:
        if name == axis:
            return {"editions": n, "channels": ch}
    return {}


def rank_spines(spines, script):
    """스파인 목록을 **이 영상에 맞는 순서**로 정렬한다.

    ★기존 동작을 깨지 않는다: 판정이 안 되면 목록을 그대로 돌려준다(폴백).
      사장님 확정(2026-08-20): "판정되면 그 스타일, 안 되면 지금처럼 목록 앞 2개".
    ★정렬만 한다 — 거르지 않는다. 거르면 "고른 게 조용히 사라지는" 사고가 난다
      (2026-08-17 실사고: 카테고리 잠금이 고른 스타일 2개를 버렸다).
    """
    want = spine_name_for(script)
    if not want:
        return list(spines or [])
    hit = [s for s in (spines or []) if (s.get("name") or "") == want]
    rest = [s for s in (spines or []) if (s.get("name") or "") != want]
    return hit + rest
