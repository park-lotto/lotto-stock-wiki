# -*- coding: utf-8 -*-
"""차량템 축 — 2026-08-28 사장님 결정 "차량템 별도 축 신설".

## 왜 축을 또 가르나 (발굴 실측)
차량용품 채널 12개를 새로 발굴했는데(남자마켓 3,310만·차츄 4,710만·안녕형들 1.16억),
그 실제 제목 30편을 현행 판정기에 넣으면:

    기타 23편(76.7%) · 장비템 5편 · 홈템 2편

**A급 차량용품이 한 편도 안 잡힌다** — 유막제거·발수코팅·햇빛가리개·거치대가 전부 '기타'.
장비템 5편은 전부 '차박'·'루프탑텐트' 어휘에 우연히 걸린 것이다.

## 왜 장비템에 흡수하지 않나 (사장님 결정)
장비템 = **집 밖 현장**(포크레인·용접기·석고보드·예초기)
차량템 = **차 안팎**(세차·거치대·차박)
제품군도 시청자도 다르고, 대본 스파인을 따로 줄 수 있어야 한다.

## 제목 공식 (통과 채널 실제 제목에서 수확)
반복 어휘 실측: 차박 46 · 자동차 26 · 차량용품(추천) 20 · 차량꿀템 15 · 세차용품 8
  · 소유격 전환   "차에 이걸 ~했더니" / "15년된 제 차에도 ~ 설치했더니"
  · 가격 앞세우기 "2만원대 햇빛가리개" / "차량용가습기를 1만4천원에"
  · 계절 트리거   "장마 오기 전에 미리" (차량템 고유 — 살림축엔 없다)
  · 단발 해결     "이거 하나로 끝" / "칙 뿌리고 헹구면 끝"
  · 차종 지정     "카니발 9인승" / "그랜저 GN7" / "GV80 오너라면"

## ⚠️ 판정 함정 (발굴에서 실측으로 확인)
★키워드 개수로 판정하면 **정답이 탈락한다**. 실측:
    블박고수(사고영상 컴필) 차 관련어 13/25  ← 제품을 안 판다
    카진남(운전 상식)       13/25            ← 판매 아님
    AnyHome(진짜 판매채널)   8/25            ← 이게 정답인데 점수가 낮다
그래서 '차 관련어가 많다'가 아니라 **차량 제품 어휘 자체**를 신호로 쓴다
(장비템과 같은 방식 — 0순위-B: 판정 방식을 두 벌로 만들지 않는다).

★짧은 말 금지. "차" ⊂ 홍차·유모차·주차·기차·차례 / "잭" ⊂ 잭슨 /
  "매트" ⊂ 요가매트 / "커버" ⊂ 이불커버. 전부 **긴 복합어**로만 인정한다.
"""
from shopping_shorts.categorize import categorize, ctype_of


# ── 발굴 실측 제목 (2026-08-28, 유튜브 API로 확인한 실제 업로드) ──────────────
REAL_CAR_TITLES = [
    ("남자마켓", "차량꿀템 3가지"),
    ("남자마켓", "와이퍼 심폐소생 하는법"),
    ("안녕형들", "2만원대 차량용 햇빛가리개 써봤습니다"),
    ("안녕형들", "밤에 보면 진짜 기절하는 차량용 커버"),
    ("셀로프라자", "차량용가습기를 1만4천원에 산다고?"),
    ("셀로프라자", "사계절 한 방에 막아주는 전동 가리개"),
    ("소낙스", "장마 오기 전에 미리 유막제거하세요"),
    ("소낙스", "타이어 갈변제거? 이거 하나로 끝"),
    ("차츄", "맥세이프 거치대 안 쓰는 사람이라면?"),
    ("차츄", "저렴한데 성능까지 좋은 유리발수 코팅제"),
    ("로드네스트", "카니발 9인승 차박, 매트 하나면 시공 없이"),
    ("크레이지 몬스터", "더 뉴 그랜저 D컷 핸들커버"),
    ("크레이지 몬스터", "카시트 보호매트"),
    ("픽스글로벌", "GV80 오너라면 이런 거치"),
]


def test_차량용품_실측제목이_차량템으로_간다():
    """회수율 — 발굴 실측 제목의 과반이 차량템이어야 한다.

    전부를 요구하지 않는 이유: "차 위에 원룸을 달았더니"처럼 제품어가 아예 없는
    제목이 섞여 있다. 그런 건 제목만으로는 판정할 수 없고, 억지로 잡으려 하면
    '차' 같은 짧은 말을 넣게 돼 홍차·유모차를 통째로 먹는다(실측 함정).
    """
    got = [(t, categorize(ch, t)) for ch, t in REAL_CAR_TITLES]
    hit = [t for t, c in got if c == "차량템"]
    miss = [(t, c) for t, c in got if c != "차량템"]
    assert len(hit) >= 10, (
        "차량템 회수 %d/%d — 놓친 것:\n" % (len(hit), len(REAL_CAR_TITLES))
        + "\n".join("    %-46s → %s" % (t, c) for t, c in miss))


def test_차량템은_제품형이다():
    """장비템과 같다 — 제품 하나를 보여주고 파는 구성."""
    assert ctype_of("차량템") == "제품형"


# ── 오탐 방어 (짧은 말이 다른 맥락을 먹지 않는지) ─────────────────────────────
NOT_CAR = [
    ("살림메모", "홍차 우리는 법 아세요?"),
    ("육아템", "유모차 정리 이렇게 하세요"),
    ("맘스쿡", "기차 여행 필수템"),
    ("살림도사", "이불커버 갈아끼우는 꿀팁"),
    ("요가라이프", "요가매트 세탁하는 법"),
    ("주차장뉴스", "주차 잘하는 법"),
    ("생활백서", "차례상 차리는 순서"),
]


def test_짧은말_오탐이_없다():
    """'차'·'매트'·'커버' 같은 짧은 말로 판정하면 이것들이 전부 차량템이 된다."""
    bad = [(t, categorize(ch, t)) for ch, t in NOT_CAR
           if categorize(ch, t) == "차량템"]
    assert not bad, "차량템 오탐:\n" + "\n".join("    %s → %s" % b for b in bad)


def test_사고영상_운전상식은_차량템이_아니다():
    """★발굴 실측 함정 — 차 관련어는 많지만 **제품을 안 판다**.
    블박고수(차 관련어 13/25)·카진남(13/25)이 진짜 판매채널 AnyHome(8/25)보다
    점수가 높았다. 키워드 개수로 판정했으면 이쪽이 통과했을 것이다."""
    cases = [
        ("블박고수", "이 車 진짜 미쳤네요 블랙박스 사고 영상"),
        ("한문철TV", "이 사고 과실 몇대몇일까요"),
        ("카진남", "고속도로에서 이렇게 하면 벌점입니다"),
        ("차본주의", "테슬라 신차 공개 소식"),
    ]
    bad = [(t, categorize(ch, t)) for ch, t in cases
           if categorize(ch, t) == "차량템"]
    assert not bad, "판매 아닌 것이 차량템으로:\n" + "\n".join("    %s → %s" % b for b in bad)


def test_장비템_본진을_뺏지_않는다():
    """★0순위-B — 새 축이 기존 축을 먹으면 안 된다.
    장비템 = 집 밖 현장. 차량템이 생겨도 포크레인·용접기는 그대로 장비템이다."""
    cases = [
        ("만물상점", "미니포크레인 한 대면 끝나는 작업"),
        ("쇼핑만물상", "레이저용접기 이게 진짜 물건입니다"),
        ("만물상점", "석고보드 타공기로 뚫어봤습니다"),
        ("공구세상", "예초기 날 교체하는 법"),
    ]
    got = [(t, categorize(ch, t)) for ch, t in cases]
    bad = [(t, c) for t, c in got if c != "장비템"]
    assert not bad, "장비템을 뺏겼다:\n" + "\n".join("    %s → %s" % b for b in bad)


def test_홈템_본진을_뺏지_않는다():
    """집 안 살림은 그대로 홈템이어야 한다."""
    cases = [
        ("살림꿀팁", "주방 정리 이 수납함 하나로 끝"),
        ("리빙템", "욕실 곰팡이 제거제 써봤습니다"),
    ]
    bad = [(t, categorize(ch, t)) for ch, t in cases
           if categorize(ch, t) == "차량템"]
    assert not bad, "홈템을 뺏겼다:\n" + "\n".join("    %s → %s" % b for b in bad)
