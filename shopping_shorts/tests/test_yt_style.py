"""유튜브 채널 스타일 축 (2026-08-19) — 사장님 "유튜브는 채널 스타일별로 나누고 싶어".

왜 별도 축인가:
인스타는 **제품 카테고리**(홈템·레시피·뷰티)로 나누는 게 맞지만, 유튜브 썰쇼핑은
같은 홈템 제품을 다루면서도 **채널마다 화법이 통째로 다르다**(2026-08-19 전사 실측).
살림킹왕짱은 오용형이면서 동시에 홈템이다 — 둘은 **다른 질문에 대한 답**이라
한 칸에 넣으면 서로를 잡아먹는다.
→ `category`(제품, 인스타·유튜브 공용)는 그대로 두고 `yt_style`(화법, 유튜브 전용)을 더한다.
   교차 조회가 가능해진다: "썰쇼핑 중 홈템".

스타일 3종(사장님 지시):
  썰쇼핑     — 지금 있는 썰쇼핑 채널들(은폐형 이븐쇼핑류 + 오용형 살림킹왕짱류)
  연예인결합  — 연예인/셀럽 + 제품 쇼핑쇼츠
  레시피쇼핑  — 음식/레시피 + 제품 쇼핑쇼츠

판정 순서(채널 우선 + 영상 보조):
  ① channel_styles에 못 박힌 채널이면 그 스타일
  ② 없으면 제목 신호로 판정
  ③ 그래도 없으면 ''(빈값) — '기타'라는 가짜 스타일을 만들지 않는다
"""
import pytest

from shopping_shorts.yt_style import yt_style, STYLES


def test_스타일_3종이_정의돼있다():
    assert set(STYLES) == {"썰쇼핑", "연예인결합", "레시피쇼핑"}


# ── ① 채널 우선 ──────────────────────────────────────────────────────────
def test_채널이_못박혀있으면_그_스타일():
    """★채널이 스타일을 지킨다는 게 이 바닥 실측이다(살림킹왕짱 84편이 한 공식).

    제목이 밋밋해도 채널로 잡아야 한다 — 이븐쇼핑 실측: 제목만으로는 12/12가 '기타'였다."""
    chan = {"이븐쇼핑": "썰쇼핑"}
    assert yt_style("이븐쇼핑", "이건 진짜 신기하네요", channel_styles=chan) == "썰쇼핑"


def test_채널_지정이_제목판정을_이긴다():
    """사람이 못 박은 게 자동 판정보다 우선이다(channel_categories와 같은 규칙)."""
    chan = {"어떤채널": "연예인결합"}
    assert yt_style("어떤채널", "제조사도 예상 못한 미친 활용법", channel_styles=chan) == "연예인결합"


# ── ② 영상 보조 — 썰쇼핑 ──────────────────────────────────────────────────
def test_은폐형_실측제목이_썰쇼핑():
    """이븐쇼핑 라이브 실측 제목."""
    for t in ["요아정 망하게 한 한국 천재의 발명품",
              "미국 천재가 만들어 떼돈 번 제품의 정체",
              "엄지 하나로 떼돈 번 일본 천재의 발명품"]:
        assert yt_style("이븐쇼핑", t) == "썰쇼핑", t


def test_오용형_실측제목이_썰쇼핑():
    """살림킹왕짱 라이브 실측 제목 — 은폐형과 하위 갈래가 다르지만 같은 썰쇼핑이다."""
    for t in ["개발자도 예상 못한 사용법 #옷수선",
              "다이소도 예상 못한 미친 활용법 #살림템 #공간활용",
              "제조사도 몰래 따라한 사용법 #주방템"]:
        assert yt_style("살림킹왕짱", t) == "썰쇼핑", t


# ── ② 영상 보조 — 연예인결합 ──────────────────────────────────────────────
def test_연예인과_제품이_함께_있어야_연예인결합():
    assert yt_style("스타템", "아이유가 쓰는 화장품 뭔지 아세요") == "연예인결합"
    assert yt_style("셀럽픽", "연예인들 애용템 추천") == "연예인결합"


def test_연예인만_있고_제품이_없으면_아니다():
    """★순수 연예 뉴스·가십은 쇼핑이 아니다. 이게 핵심 거름망이다."""
    assert yt_style("연예뉴스", "아이유 신곡 발표 현장") != "연예인결합"
    assert yt_style("연예소식", "손흥민 경기 하이라이트") != "연예인결합"


# ── ② 영상 보조 — 레시피쇼핑 ──────────────────────────────────────────────
def test_음식과_제품이_함께_있어야_레시피쇼핑():
    assert yt_style("자취요리", "자취생 요리 필수템 추천") == "레시피쇼핑"
    assert yt_style("쿡템", "에어프라이어 요리 꿀템 리뷰") == "레시피쇼핑"


def test_순수레시피는_아니다():
    """★순수 요리 채널은 제품을 안 판다 — 레시피쇼핑이 아니다."""
    assert yt_style("백종원따라하기", "김치찌개 맛있게 끓이는 법") != "레시피쇼핑"
    assert yt_style("자취요리", "간단 계란 볶음 레시피") != "레시피쇼핑"


# ── ③ 못 잡으면 빈값 ─────────────────────────────────────────────────────
def test_못_잡으면_빈값이다():
    """'기타'라는 가짜 스타일을 만들지 않는다 — 없으면 없다고 한다."""
    assert yt_style("아무채널", "오늘 날씨가 좋네요") == ""
    assert yt_style("", "") == ""


def test_교양뉴스는_스타일이_없다():
    """썰쇼핑 차단어(_HOOK_BLOCK)를 공유한다 — 0순위-B, 판단은 한 곳."""
    assert yt_style("KNN NEWS", "\"21세기 사상 최악의 발명품\" 머스크 미운털") == ""


# ── 축 독립성 ───────────────────────────────────────────────────────────
def test_제품카테고리_축을_건드리지_않는다():
    """★두 축은 서로 다른 질문이다. category는 그대로여야 교차 조회가 된다."""
    from shopping_shorts.categorize import categorize
    name, title = "살림킹왕짱", "개발자도 예상 못한 사용법 #옷수선"
    assert categorize(name, title) == "오용형"      # 기존 축 그대로
    assert yt_style(name, title) == "썰쇼핑"        # 새 축은 별개


