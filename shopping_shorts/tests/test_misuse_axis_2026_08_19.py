# -*- coding: utf-8 -*-
"""발굴 3차 어휘축 — **실측 제목**으로 판정 구멍을 못 박는다(2026-08-19).

근거: 후보 채널 8곳(이왜템·나만또모르고있었지·와이거뭐냐·요새난리·이거였네·
썰칩12·썰쇼템·짤이야)의 실제 업로드 제목. 확장 전 판정 통과율은 **48%**였다.

★왜 목록이 아니라 제목을 박아두나: 어휘 목록만 테스트하면 "단어가 있다"만 지키고
  **실제 제목이 걸리는가**는 안 지켜진다. 띄어쓰기 변형("예상 못 한")이 통째로 새던
  것이 정확히 그 실패였다 — 단어는 있었는데 제목이 안 걸렸다.
"""
from shopping_shorts import categorize as cz

SUL = ("오용형", "제품정체형")

# 확장으로 **새로 걸리게 된** 제목들. 각 줄 끝은 없던 조각.
NEWLY_CAUGHT = [
    ("제조사도 예상 못 한 뜻밖의 활용법", "띄어쓰기 변형 '예상 못 한'"),
    ("살림 고수들도 예상 못 한 뜻밖의 활용법", "권위자 '살림 고수'"),
    ("요리 고수들도 감탄한 완벽한 활용법", "권위자 '요리 고수'"),
    ("기획자도 예상 못한 신박한 사용법", "권위자 '기획자'"),
    ("제작자도 예상 못한 뜻밖의 사용법", "권위자 '제작자'"),
    ("만든 사람도 예상못한 의외의 사용법", "권위자 '만든 사람'"),
    ("이케아 디자이너도 예상치 못한 사용법", "부정어 '예상치 못한'"),
    ("이케아 직원도 몰래쓰는 활용법", "부정어 '몰래쓰는'"),
    ("다이소도 놀라버린 압축봉 활용 방법", "부정어 '놀라버린'"),
    ("다이소 마케팅 담당자도 당황해버린 천재의 활용법", "부정어 '당황해버린'"),
    ("전 세계가 당황한 한국 천재의 미친 활용법", "권위자 '전 세계'"),
    ("다이소도 감탄한 반전의 스티커", "귀결어 '반전'"),
    ("제조사도 예상못한 반전 활용도", "귀결어 '활용도'"),
]


def test_실측_제목이_걸린다():
    miss = [(t, why) for t, why in NEWLY_CAUGHT if cz.categorize("", t) not in SUL]
    assert not miss, "실제 채널 제목이 안 걸린다: %s" % miss


# 대조군 — 공식은 비슷한데 쇼핑이 아니다. 넓힌 어휘가 여기로 새면 안 된다.
NOT_SUL = [
    "머스크가 예상 못한 화성 탐사선의 정체",
    "NASA도 놀란 우주 망원경의 활용법",
    "롤 프로들도 감탄한 미친 활용법 (게임 공략)",
    "피파 고인물들도 놀란 신박한 사용법",
    "설교말씀 | 하나님이 예비하신 뜻밖의 방법",
    "역사 다큐: 발명가 에디슨도 몰랐던 아이디어",
    "오늘의 뉴스 브리핑 - 기자도 예상 못한 결과",
]


def test_대조군은_안_걸린다():
    fp = [t for t in NOT_SUL if cz.categorize("", t) in SUL]
    assert not fp, "쇼핑이 아닌 제목이 통과했다: %s" % fp


def test_롤은_차단어가_아니다():
    """★'롤'을 차단어로 넣으면 진짜 쇼핑 제목이 죽는다(실측 채널 '요새난리')."""
    assert "롤" not in cz._HOOK_BLOCK
    # 이 제목은 공식 미충족이라 오용형은 아니지만, **차단으로 죽어서는 안 된다**.
    assert cz.categorize("", "롤 비닐을 박살내버린 분리수거 필수템") != "차단"
