def main():
    s = Store(DB_PATH)
    # v2 시드 제거(원래 학습 스파인 5개는 이름이 달라 보존됨)
    removed = 0
    with s._conn() as c:
        for nm in _V2_NAMES:
            removed += c.execute("DELETE FROM spine WHERE name=?", (nm,)).rowcount
    existing = {sp["name"] for sp in s.list_spines()}
    added = skipped = 0
    for name, fit, appeal, beats in SPINES:
        if name in existing:
            skipped += 1
            continue
        sid = s.add_spine(name, situation_type=appeal, beat_chain=beats,
                          emotion_arc=beats[3], appeal=appeal,
                          fit_categories=fit, status="approved")
        with s._conn() as c:
            c.execute("UPDATE spine SET source_count=? WHERE id=?", (_CURATED, sid))
        added += 1
    print(f"seed_spines_v3: removed_v2={removed} added={added} skipped={skipped}")


if __name__ == "__main__":
    main()
