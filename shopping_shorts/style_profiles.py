_TRIO = ["maison", "chae", "standard"]


def _block(guide, fewshot):
    shots = "\n\n".join(f"스타일 예시{i+1} ({v}):\n{t}"
                        for i, (v, t) in enumerate(fewshot))
    return f"\n{guide}\n[스타일 예시 — 실제 히트 대본 3편]\n{shots}\n"


def _maison_block():
    return _block(_MAISON_GUIDE, _MAISON_FEWSHOT)


def active_style():
    """현재 스타일 모드. off/0/빈값이면 None(무주입). 기본 'trio'(후보별 3각 배정)."""
    v = (os.environ.get("SCRIPT_STYLE") or "trio").strip().lower()
    return None if v in ("off", "0", "") else v


def candidate_style(idx):
    """후보 인덱스(0부터) → 스타일 이름. trio면 3각 순환, 단일 스타일이면 그 스타일.
    off면 None."""
    mode = active_style()
    if mode is None:
        return None
    if mode == "trio":
        return _TRIO[idx % len(_TRIO)]
    return mode if mode in _STYLES else "maison"


def style_penalty(narrations):
    """스타일 이탈 감점(0~0.5) — 추천이 리라이트 실패 후보를 고르는 걸 막는다.

    2026-08-05 실사고(job 31b394c4): 후보 3개 중 리라이트에 실패해 옛 카피체로 남은
    후보가 ★추천으로 뽑혔다(채점이 스타일을 안 봄). 합쇼체(~습니다)와 명령형 훅만
    가볍게 감점한다 — 스타일 off면 0(회귀 없음)."""
    import re
    if not active_style() or not narrations:
        return 0.0
    joined = " ".join(narrations)
    # 합쇼체 종결(~습니다/~ㅂ니다) — '니다'로 닫히는 문장을 센다
    p = 0.06 * len(re.findall(r"니다\s*[.!?…]", joined + " "))
    first = (narrations[0] or "").strip()
    if re.search(r"(하세요|보세요|쓰세요|마세요)", first.split(".")[0]) and \
            not re.match(r"(와|아니|헐|세상에|저 이거|이거)", first):
        p += 0.15
    return min(p, 0.5)


