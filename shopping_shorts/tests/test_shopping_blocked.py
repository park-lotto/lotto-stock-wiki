# -*- coding: utf-8 -*-
"""쇼핑이 아닌 소재는 카테고리에 안 들어온다 (2026-09-04 사장님).

제보: "현재 카테고리들 이상한게 너무 많이 섞여 끼어있다. 이것부터 정리하는게 우선"
화면 첫 장에서 바로 드러난 것들이 아래 BAD다(조회수 상위였다).

★뿌리 두 개:
1. 차단이 _is_sul_ext에만 있었다 → 기존 _is_hook_product가 **먼저** 잡으면 통째로 무력.
   ("김혜은이 피부과 안 가고 …"가 _is_hook_product=True로 제품정체형이 됐다)
   → _shopping_blocked 한 곳으로 뽑아 두 관문이 함께 본다(0순위-B).
2. 나라 이름이 권위자 목록에 있었다 → (한국·일본)+(난리)로 "일본 여배우"가 통과.
   "한국 천재가 만들어…"는 '천재'가 잡으므로 나라 이름을 빼도 손실이 없다.
"""
import pytest

from shopping_shorts.categorize import categorize

SUL = ("제품정체형", "오용형")

BAD = [
    ("신비한 이야기꾼", "아내가 아파서 25년 동안 숨겨왔던 숲의 정체"),      # 자연·사연
    ("국뽕한꼬집", "한국 여행중 찍은 사진에 난리 난 일본 여배우"),          # 연예
    ("숏핑증독", "김혜은이 피부과 안 가고 집에서 바세린이랑 이것 섞어 썼더니 충격적 변화?"),
    ("셀템픽", "로제가 아침마다 화장실에서 만지는 '이것'의 정체?!"),        # 연예인 뷰티
    ("운세채널", "2026년 하반기 1975년생 52세 토끼띠운세 정체"),           # 운세
]

GOOD = [
    ("이븐쇼핑", "한국 천재가 만들어 돈방석 앉은 제품"),
    ("인생갓템", "조용히 떼돈버는 사람들의 비밀"),
    ("쇼핑천재", "제조사도 당황한 의외의 사용자"),          # 권위자+반응 (후킹명사 없음)
    ("공구채널", "몽키 작업하다 빡친 천재가 만들어 버린 공구"),
    ("럭키박스", "이비인후과 갔다가 빡친 개발자가 직접 만든 미친 귀이개"),
]


@pytest.mark.parametrize("name,cap", BAD)
def test_쇼핑이_아니면_썰쇼핑이_아니다(name, cap):
    got = categorize(name, cap)
    assert got not in SUL, f"쇼핑 아닌 것이 {got}으로 들어왔다: {cap[:34]}"


@pytest.mark.parametrize("name,cap", GOOD)
def test_진짜는_그대로_잡는다(name, cap):
    """★차단을 조이다 진짜를 죽이면 안 된다 — 실측으로 106편이 한 번 빠졌다.
    특히 '권위자+반응'(후킹명사 없음) 조합을 빼면 이 장르의 절반이 사라진다."""
    assert categorize(name, cap) in SUL, f"진짜 썰쇼핑을 놓쳤다: {cap[:34]}"
