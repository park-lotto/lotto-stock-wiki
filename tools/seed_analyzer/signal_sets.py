# -*- coding: utf-8 -*-
"""고조 신호어 **세트(프리셋)** — 코드가 세트를 골라 칸마다 순번으로 준다 (2026-09-22 사장님).

사장님: "시그널에는 같은 단어를 쓰는게 맞아. 그게 터지는 포인트고 사람들이 익숙하고 좋아하는
        지점이야 / 골라서 쓰는것도 안지키면 순번으로 세트를 만들어서 해주던가
        / a세트 1심지어 2이게 대박인게 3이게 끝이아니라 4. 정말 미친포인트는 따로있는데"

★왜 세트인가: 신호어는 **골라 쓰게 하면 안 지켜진다** — 실측 2026-09-22, 모델에게 후보를
  주고 고르게 했더니 2편 모두 "이게 진짜 말도 안 되는 게" 하나만 썼다(가장 흔한 것으로 쏠림).
  세트로 묶어 **코드가 칸 순서대로 박아 주면** 쏠림이 원천 차단되고, 회원마다 다른 세트가 간다.

★세트 안에서 **세기가 올라가야** 한다: 1번은 가볍게(심지어) → 마지막은 제일 세게
  (진짜 미친 포인트는 따로 있는데). 고조는 뒤로 갈수록 세지는 자리이므로 순서가 곧 강도다.

★낱말은 전부 실측이다(썰계열 261편 + 등록 스파인 368개, 17.8만 자):
  심지어 158 · 진짜 미친 포인트는 49 · 근데 진짜 충격적인 포인트는 40 · 이게 말도 안 되는게 35 ·
  게다가 31 · 근데 진짜 미친 포인트는 30 · 이게 미친 포인트인게 24 · 대박인 건 9 · 따로 있는데 9 …
  지어낸 말은 한 개도 없다.
"""
import zlib

# 세트마다 [1번칸, 2번칸, 3번칸, 4번칸] — 뒤로 갈수록 세진다.
# ★빈 문자열("")은 **신호어를 안 붙인다**는 뜻이다. 매 칸에 붙으면 기계처럼 보이므로
#   세트마다 한 자리는 비워 둔다(2026-09-22 실측: 전부 붙인 편이 가장 기계 같았다).
try:   # ★정의는 shopping_shorts/story_writer.py 한 곳(0순위-B). 여기는 시험대용 별칭이다.
    from shopping_shorts.story_writer import YT_SETS as SETS
except Exception:  # noqa: BLE001
    SETS = {"A": ["이게 말도 안 되는게", "심지어", "근데 진짜 충격적인 포인트는"]}


def make_key(customer_id, work_id=""):
    """신호세트를 고르는 키 — **고객 + 작업**. 몇 번째 안인지는 pick_set(nth)로 따로 준다.
    ★고객만 넣으면 같은 고객이 여러 작업을 해도 세트가 고정된다(2026-09-22 실측:
      제품 3종을 같은 키로 돌렸더니 고조2 신호어가 전부 '게다가'로 같았다)."""
    return "%s|%s" % (customer_id, work_id)


def pick_set(key, nth=0):
    """세트를 **정해진 규칙으로** 고른다(무작위 아님 — 같은 입력=같은 세트).

    ★nth(같은 작업의 몇 번째 안인가)는 해시에 섞지 않고 **순번으로 더한다**.
      해시에 섞으면 1안과 3안이 우연히 같은 세트가 된다(2026-09-22 실측: 57번 회원 3안 = E·C·E).
      순번으로 더하면 한 작업 안에서는 **반드시 다른 세트**가 나온다.
    """
    names = sorted(SETS)
    base = zlib.crc32(str(key).encode("utf-8")) % len(names)
    i = (base + int(nth)) % len(names)
    return names[i], SETS[names[i]]


def signals_for(key, n_beats, nth=0):
    """고조 칸 수만큼 신호어를 돌려준다. 칸이 세트보다 많으면 앞에서부터 다시 쓴다."""
    name, seq = pick_set(key, nth)
    return name, [seq[i % len(seq)] for i in range(max(0, n_beats))]


if __name__ == "__main__":
    print("세트 %d개" % len(SETS))
    print("같은 고객이 한 작업에서 3안을 뽑을 때 (순번으로 더해 반드시 갈린다):")
    for n in range(3):
        name, sig = signals_for(make_key(57, "w123"), 3, n)
        print("  %d안  세트 %s  %s" % (n + 1, name, sig))
    print("같은 씨앗을 쓴 다른 고객 12명:")
    got = [pick_set(make_key(c, "w123"))[0] for c in range(1, 13)]
    print("  ", got, "→ 서로 다른 세트", len(set(got)), "/12")
