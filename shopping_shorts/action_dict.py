ACTION_VOCAB = list(ACTION_KEYWORDS)


def _hits(text, kws):
    return sum(1 for kw in kws if kw in text)


def tag_action(text):
    """text에서 가장 많이 걸린 행위 동사 반환. 하나도 없으면 None."""
    if not text:
        return None
    best, best_score = None, 0
    for action, kws in ACTION_KEYWORDS.items():
        s = _hits(text, kws)
        if s > best_score:   # 엄격한 > : 동점은 선언 순서 유지
            best, best_score = action, s
    return best
