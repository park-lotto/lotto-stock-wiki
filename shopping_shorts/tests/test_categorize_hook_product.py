"""제품정체형(후킹형 쇼핑) 카테고리 — 2026-08-17 사장님 "이븐쇼핑같은 스타일이 대세".

왜 새 축이 필요한가 (라이브 실측):
이븐쇼핑(UClecY6IhcjwmCBJHiZ2-cTg) 최근 숏폼 30건을 현행 categorize에 넣으면
**제목만으로는 12/12 전부 '기타'** 다. "엄지 하나로 떼돈 번 일본 천재의 발명품"에
살림·주방·꿀템 같은 제품어가 하나도 없기 때문이다. 이 장르는 후킹이 목적이라
**제목에 제품명을 일부러 숨긴다.**

그런데 이건 잡음이 아니라 사장님이 원하는 소재다(짤+쇼핑을 엮는 결).
기존 4분류(홈템/레시피/뷰티/기타)엔 담을 칸이 없어 전부 '기타'로 떨어져 있었다.
같은 이유로 슈스스TV(에르메스 추천)·단순할 현(자취템)도 '기타'에 묻혀 있다.
"""
from shopping_shorts.categorize import categorize, ctype_of


# 라이브에서 실제로 수집된 이븐쇼핑 계열 제목(2026-08-17 실측)
REAL_TITLES = [
    "엄지 하나로 떼돈 번 일본 천재의 발명품",
    "요아정 망하게 한 한국 천재의 발명품",
    "국자 하나로 떼돈 번 캐나다 천재의 발명품",
    "일본 천재가 만들어 떼돈 번 제품의 정체",
    "다이소도 놀란 한국 천재의 발명품",
    "화병을 산산조각 내버린 천재의 발명품",
    "단순한 기능 추가로 떼돈 번 천재의 발명품",
]


def test_real_hook_titles_are_not_기타():
    """실측 제목이 '기타'로 빠지면 안 된다 — 이게 이 작업의 존재 이유."""
    for t in REAL_TITLES:
        assert categorize("이븐쇼핑", t) == "제품정체형", f"'{t}' 가 분류에서 샜다"


def test_channel_name_alone_is_enough():
    """제목이 밋밋해도 채널명이 이 장르면 잡아야 한다."""
    assert categorize("이븐쇼핑", "이건 진짜 신기하네요") == "제품정체형"


def test_교양_발명채널은_제외():
    """오탐 차단(실측): 뉴스·지식 교양 채널도 '발명품'을 말한다.

    라이브 검색에서 KNN NEWS('21세기 최악의 발명품')·지식북(구구단)·
    1분홀릭(NASA)이 같이 걸렸다. 이건 쇼핑 소재가 아니다."""
    assert categorize("KNN NEWS", "\"21세기 사상 최악의 발명품\" 머스크 미운털") != "제품정체형"
    assert categorize("지식북", "100년 전에 발명된 구구단 치트키?") != "제품정체형"
    assert categorize("1분홀릭", "나사가 우주에서 돌을 잡기 위해 개발한 역대급 발명품 #NASA") != "제품정체형"


def test_기존_카테고리를_빼앗지_않는다():
    """★회귀 방지: 새 축이 홈템·레시피·뷰티를 잡아먹으면 안 된다.

    제품어가 뚜렷하면 기존 분류가 이긴다 — 새 축은 '기타'로 빠지던 것만 건진다."""
    assert categorize("살림템 채널", "주방 정리수납 꿀템 추천") == "홈템"
    assert categorize("자취요리", "간단 계란 볶음 레시피") == "레시피"
    assert categorize("뷰티채널", "메이크업 쿠션 추천") == "뷰티"


def test_진짜_기타는_그대로_기타():
    """짤·이슈·연예 클립은 여전히 기타여야 한다(이건 실제 잡음)."""
    assert categorize("덕칼럼", "'데뷔'를 너무 일찍 해버린 아이돌들") == "기타"
    assert categorize("앙~유진", "무대에서 모자를 쓰고 나온 유진이") == "기타"
    assert categorize("JTBC News", "들쥐 고기 먹고 병원 입원한 세 자매") == "기타"


def test_ctype_매핑_존재():
    """새 topic도 ctype 축에 자리가 있어야 한다(KeyError 방지)."""
    assert ctype_of("제품정체형") == "제품형"
