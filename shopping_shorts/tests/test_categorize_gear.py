def test_차량어휘_오탐방지():
    """★짧고 흔한 말은 다른 맥락을 먹는다 — 기존 사전이 '드릴/공구'에서 겪은 그 함정.

    아래는 전부 장비템이 **아니어야** 한다. 하나라도 장비템이면 어휘가 너무 짧은 것이다.
    """
    NOT_GEAR = [
        ("요리채널", "차 한잔 마시며 만드는 홍차 레시피"),      # '차' 단독
        ("살림채널", "주차장에서 유모차 접는 법 #육아템"),       # '주차'·'유모차'
        ("뷰티채널", "잭슨 메이크업 따라하기"),                  # '잭' ⊂ 잭슨
        ("일상채널", "카메라 앞에서 안 떠는 법"),                # '카메라' 단독
        ("게임채널", "배터리 광고 나오는 게임 실화냐"),          # '배터리' 단독
    ]
    for ch, t in NOT_GEAR:
        got = categorize(ch, t)
        assert got != "장비템", f"오탐: '{t}' 가 장비템으로 잡혔다 (got={got})"


