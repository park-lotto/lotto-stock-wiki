_CAP_W = 3   # 캡션(영상별 신호) 가중
_NAME_W = 1  # 채널명(도배 가능) 가중


def _hits(text, kws):
    return sum(1 for kw in kws if kw in text)


def categorize(name, caption=""):
    """채널명+캡션 → topic. 캡션은 전체 키워드(우선 가중), 채널명은 강한 키워드만.
    최고점 채택, 전부 0이면 '기타'."""
    name_t = (name or "").lower()
    cap_t = (caption or "").lower()
    best, best_score = "기타", 0
    for category, kws in KEYWORDS.items():
        cap_score = _hits(cap_t, kws) * _CAP_W
        name_score = _hits(name_t, NAME_KEYWORDS[category]) * _NAME_W
        score = cap_score + name_score
        if score > best_score:          # 엄격한 > → 동점은 선언 순서(앞선 것) 유지
            best, best_score = category, score
    return best


def ctype_of(topic):
    """topic → 유형(비법형/제품형/혼합형/기타)."""
    return TOPIC_CTYPE.get(topic, "기타")


def classify(name, caption=""):
    """topic·ctype 동시 반환: {'topic':..., 'ctype':...}."""
    topic = categorize(name, caption)
    return {"topic": topic, "ctype": ctype_of(topic)}
