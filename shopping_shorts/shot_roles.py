"""shot_role 어휘 — **여기 한 곳에서만 정한다**(CLAUDE.md 0순위-B).

## 왜 이 모듈이 생겼나 (2026-08-20)

같은 어휘가 네 군데에 따로 적혀 있었다:

    frame_script.py   태깅 프롬프트 문구 + JSON 스키마 enum
    script_extract.py _SHOT_ROLE_VOCAB / _SHOT_ROLE_ALIASES
    edit_plan.py      슬롯의 roles=["사용중"] · _BLOCK_ROLES
    backbone.py       _BEAT_ROLE_SHOTS

한 곳에 값을 더해도 나머지가 모르면 **새 값이 '기타'로 떨어지거나 슬롯에 안 걸린다.**
실제로 옛 값 `조리`가 라이브에 220건 남아 있다 — `_norm_shot_role`이 흡수하게 돼 있는데도
저장 경로를 안 타서 그대로다.

## 축을 왜 늘렸나 (실측)

라이브 7,813장면의 분포가 이랬다:

    사용중 3,541(45.3%) · 완성 1,199(15.3%) · (없음) 1,190(15.2%)
    기타 695(8.9%) · after 603(7.7%) · 조리 220(2.8%) · 문제 183 · before 182

**절반 가까이가 '사용중' 한 통**이라 "장점1 자리엔 이 장면"을 지시할 수 없었다.
'사용중' 장면설명 3,541건의 서술어를 세어 나온 갈래가 아래 다섯이다:

    설치  고정30 부착19 설치17 장착16 결합16 조립12   = 110
    정리  정리33 청소32 정돈11 수납10 제거10          = 96
    조작  조작20 회전16 조절16 터치11                 = 63
    도포  분사20 도포17                              = 37
    실증  확인35                                     = 35

★`scene_lab.html`이 이미 '사용중'을 굽기/재료/마무리로 한 겹 더 갈랐지만 그건 **요리 편향**이고
  (그 파일 주석도 "요거트·화분·선반 같은 비요리 소재에도 그대로 붙었다"고 인정한다)
  "화면 분류일 뿐 배치 로직과 무관"하다고 못 박혀 있다. 그래서 배치가 쓰는 축을 따로 세운다.

## ★`사용중`을 지우지 않았다

라이브 3,541건이 그 값으로 저장돼 있고 `edit_plan`의 슬롯이 `roles=["사용중"]`로 걸려 있다.
지우면 그 슬롯이 통째로 빈다. 그래서 `사용중`은 **다섯 갈래에 안 들어가는 일반 사용 장면**을
받는 자리로 남긴다(fail-open). 새로 태깅되는 것만 잘게 흩어진다.
"""

# 실제 사용 장면(=제품을 쓰는 구간)의 갈래. 배치에서 "사용 계열"로 함께 취급한다.
USE_ROLES = ("설치", "조작", "도포", "정리", "실증", "사용중")

# 전체 어휘. 태깅 프롬프트·JSON enum·정규화가 전부 이 하나를 본다.
SHOT_ROLES = ("before", "문제") + USE_ROLES + ("after", "완성", "기타")

# 옛 값 → 지금 값. 라이브에 남은 것만 적는다(`조리` 220건 실측).
ALIASES = {"조리": "사용중"}

# 태깅 모델에게 주는 한 줄 설명 — 프롬프트와 enum이 어긋나지 않게 여기서 함께 만든다.
DESCRIPTIONS = {
    "before": "쓰기 전 상태",
    "문제": "불편·문제를 보여주는 장면",
    "설치": "붙이고 고정하고 조립해 자리를 잡는 장면",
    "조작": "돌리고 누르고 조절해 작동시키는 장면",
    "도포": "바르고 뿌리고 붓는 장면",
    "정리": "닦고 치우고 수납하는 장면",
    "실증": "효과·성능을 눈으로 확인시키는 장면(비교·테스트)",
    "사용중": "위 다섯에 딱 안 맞는 일반적인 사용 장면",
    "after": "쓰고 난 뒤 결과",
    "완성": "완성된 모습·최종 결과물",
    "기타": "위 어디에도 안 맞음",
}


def normalize(raw):
    """알 수 없는 값은 '기타'로 떨어뜨린다(fail-open — 배치가 크래시 없이 돈다)."""
    v = (raw or "").strip()
    if v in SHOT_ROLES:
        return v
    return ALIASES.get(v, "기타")


def is_use(role):
    """이 장면이 '제품을 쓰는' 계열인가. 슬롯이 `사용중` 하나만 보던 자리를 대신한다."""
    return normalize(role) in USE_ROLES


def prompt_line():
    """태깅 프롬프트에 넣을 shot_role 설명 한 덩어리. enum과 **같은 목록**에서 만든다."""
    return "shot_role(%s 중 하나 — %s)" % (
        "/".join(SHOT_ROLES),
        " · ".join("%s=%s" % (r, DESCRIPTIONS[r]) for r in SHOT_ROLES))


def expand(roles):
    """슬롯·판정표가 요구하는 role 목록 → **실제로 매칭할 집합**.

    `사용중`을 요구하는 자리는 잘게 쪼갠 갈래(설치·조작·도포·정리·실증)도 전부 받는다.

    ★이렇게 한 이유(0순위-B): `roles=["사용중"]`로 적힌 슬롯이 `edit_plan`에 6곳,
      판정표에 3곳 = 아홉 군데다. 축을 늘릴 때마다 그 아홉 곳에 새 값을 하나씩 더하면
      언젠가 한 곳을 빠뜨린다 — 그러면 그 슬롯만 조용히 안 채워진다(에러가 안 난다).
      넓히는 판단을 **여기 하나**에 두면 슬롯 정의는 손댈 필요가 없다.

    옛 값 `조리`도 정규화를 거치므로 그대로 걸린다.
    """
    want = set()
    for r in (roles or ()):
        n = normalize(r)
        want.add(n)
        # ★넓히는 건 **`사용중`을 요구할 때뿐**이다(2026-08-20 실측으로 잡음).
        #   처음엔 "사용 계열 값이면 전부 넓힌다"로 짰는데, 그러면 `도포`를 요구해도
        #   조작·정리·설치가 전부 걸린다 = **축을 쪼개 놓고 구분을 못 한다.**
        #   실측: 뷰티 '사용' 슬롯이 ["도포","조작","사용중"]인데 크림 바르는 컷을 두고
        #   "뚜껑을 돌려 연다"(조작)를 집었다. 도포가 있든 없든 결과가 같았다.
        #   `사용중`은 갈래를 안 가리는 **폴백 이름**이라 그때만 계열 전체로 넓힌다.
        if n == "사용중":
            want.update(USE_ROLES)
    return want


def matches(role, roles):
    """장면의 shot_role이 이 슬롯이 요구하는 결에 드는가."""
    return normalize(role) in expand(roles)
