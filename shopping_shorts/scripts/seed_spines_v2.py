def main():
    s = Store(DB_PATH)
    existing = {sp["name"] for sp in s.list_spines()}
    added = skipped = 0
    for name, fit, situ, appeal, beats in SPINES:
        if name in existing:
            skipped += 1
            continue
        sid = s.add_spine(name, situation_type=situ, beat_chain=beats,
                          emotion_arc=beats[3], appeal=appeal,
                          fit_categories=fit, status="approved")
        # source_count는 add_spine 인자에 없어 직접 세팅(승격게이트 통과 마커)
        with s._conn() as c:
            c.execute("UPDATE spine SET source_count=? WHERE id=?", (_CURATED, sid))
        added += 1
    print(f"seed_spines_v2: added={added} skipped={skipped} total={len(SPINES)}")


if __name__ == "__main__":
    main()
