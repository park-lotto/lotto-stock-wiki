def main():
    st = Store(DB_PATH)
    for spec in STYLES:
        name = spec["name"]
        existing = [s for s in st.list_spines() if s["name"] == name]
        if existing:
            sp = existing[0]
            sid = sp["id"]
            st.set_spine_style(sid, beat_roles=spec["beat_roles"],
                               templates=spec["templates"],
                               chars_per_30s=spec["chars_per_30s"])
            with st._conn() as c:          # 카테고리·승인상태도 교정(기존 행을 되살린다)
                c.execute("UPDATE spine SET fit_categories_json=?, status='approved' WHERE id=?",
                          (_json.dumps(spec["fit_categories"], ensure_ascii=False), sid))
            st.update_spine_stats(sid, source_count=spec["source_count"], perf_score=0.0)
            print("이미 있어 갱신함: %s (id=%s)" % (name, sid))
            continue
        sid = st.add_spine(
            name=name,
            situation_type=spec["situation_type"],
            beat_chain=spec["beat_chain"],
            emotion_arc=spec["emotion_arc"],
            appeal=spec["appeal"],
            fit_categories=spec["fit_categories"],
            status="approved",
        )
        st.set_spine_style(sid, beat_roles=spec["beat_roles"],
                           templates=spec["templates"],
                           chars_per_30s=spec["chars_per_30s"])
        st.update_spine_stats(sid, source_count=spec["source_count"], perf_score=0.0)
        print("새로 넣음: %s (id=%s)" % (name, sid))
    return 0


