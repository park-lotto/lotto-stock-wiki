/* 주인공: 50대, 둥근 얼굴, 짧은 회색빛 머리, 동그란 안경, 셔츠(칼라+단추선). 모든 장면 공통. */
(function () {
  const { ell, P, ORANGE } = INK;
  // 얼굴. r=머리 반지름(px). o: expr, s(시작), rot, look(-1..1), sp(속도배율), parent, w
  function face(c, cx, cy, r, o = {}) {
    const a = (o.rot || 0) * Math.PI / 180, ca = Math.cos(a), sa = Math.sin(a);
    const T = (x, y) => { const X = x * r, Y = y * r; return [cx + X * ca - Y * sa, cy + X * sa + Y * ca]; };
    const ex = o.expr || "neutral", look = o.look || 0, sp = o.sp || 1, s0 = o.s || 0, w = o.w || (r < 90 ? 5 : 6);
    const par = o.parent;
    const add = (d, s, dur, x) => c.path(d, Object.assign({ s: s0 + s * sp, dur: dur * sp, w, parent: par }, x || {}));
    // 머리 (뒤 선이 비치지 않게 종이색 밑칠)
    c.mask(ell(T, 0, 0, 0.95, 1.05, { ph: 0.6 }), s0, par);
    add(ell(T, 0, 0, 0.95, 1.05, { ph: 0.6 }), 0, 0.7, { tint: "skin" });
    // 머리카락(짧은 머리, 흰머리 섞인 회색)
    add(P(T, [["M", -0.97, -0.12], ["C", -1.18, -0.85, -0.55, -1.38, 0.05, -1.3], ["C", 0.72, -1.36, 1.22, -0.82, 0.97, -0.12], ["C", 0.82, -0.5, 0.5, -0.74, 0.08, -0.74], ["C", -0.4, -0.73, -0.82, -0.5, -0.97, -0.12], ["Z"]]), 0.5, 0.55, { tint: "grey", tintOp: 0.34 });
    // 귀
    add(P(T, [["M", -0.95, -0.02], ["C", -1.14, -0.08, -1.15, 0.3, -0.93, 0.3]]), 0.95, 0.2);
    add(P(T, [["M", 0.95, -0.02], ["C", 1.14, -0.08, 1.15, 0.3, 0.93, 0.3]]), 0.98, 0.2);
    // 동그란 안경
    add(ell(T, -0.4, 0.0, 0.3, 0.28, { ph: 1 }), 1.05, 0.35);
    add(ell(T, 0.4, 0.0, 0.3, 0.28, { ph: 2 }), 1.2, 0.35);
    add(P(T, [["M", -0.1, -0.05], ["Q", 0, -0.14, 0.1, -0.05]]), 1.4, 0.12);
    add(P(T, [["M", -0.7, -0.02], ["L", -0.95, -0.06]]), 1.45, 0.1);
    add(P(T, [["M", 0.7, -0.02], ["L", 0.95, -0.06]]), 1.5, 0.1);
    // 눈
    const ey = 0.02, lx = look * 0.1;
    const dot = (x, rr, s) => add(ell(T, x + lx, ey, rr, rr, { n: 18 }), s, 0.12, { fill: "#1F1D1A", pen: false });
    if (ex === "sparkle") {
      dot(-0.4, 0.1, 1.6); dot(0.4, 0.1, 1.65);
      // 반짝: 눈 옆 네 갈래 별 (이 컷의 강조색)
      const star = (x, y, k, s) => { add(P(T, [["M", x - k, y], ["L", x + k, y]]), s, 0.2, { color: ORANGE, w: 6 }); add(P(T, [["M", x, y - k], ["L", x, y + k]]), s + 0.05, 0.2, { color: ORANGE, w: 6 }); };
      star(-0.62, -0.32, 0.17, 1.9); star(0.62, -0.32, 0.17, 2.0);
    } else if (ex === "tired") {
      add(P(T, [["M", -0.62, 0.05], ["Q", -0.4, 0.17, -0.18, 0.05]]), 1.6, 0.18); // 반쯤 감은 눈꺼풀
      add(P(T, [["M", 0.18, 0.05], ["Q", 0.4, 0.17, 0.62, 0.05]]), 1.65, 0.18);
      add(P(T, [["M", -0.55, 0.36], ["Q", -0.4, 0.42, -0.25, 0.36]]), 1.8, 0.12, { w: 4 }); // 눈 밑 그늘
      add(P(T, [["M", 0.25, 0.36], ["Q", 0.4, 0.42, 0.55, 0.36]]), 1.82, 0.12, { w: 4 });
    } else { dot(-0.4, 0.07, 1.6); dot(0.4, 0.07, 1.65); }
    // 눈썹
    if (ex === "worry" || ex === "sweat") {
      add(P(T, [["M", -0.68, -0.34], ["L", -0.2, -0.52]]), 1.7, 0.14); add(P(T, [["M", 0.2, -0.52], ["L", 0.68, -0.34]]), 1.72, 0.14);
    } else if (ex === "tired") {
      add(P(T, [["M", -0.68, -0.4], ["Q", -0.42, -0.5, -0.18, -0.42]]), 1.7, 0.14); add(P(T, [["M", 0.18, -0.42], ["Q", 0.42, -0.5, 0.68, -0.4]]), 1.72, 0.14);
    } else {
      add(P(T, [["M", -0.68, -0.43], ["Q", -0.42, -0.58, -0.16, -0.46]]), 1.7, 0.14); add(P(T, [["M", 0.16, -0.46], ["Q", 0.42, -0.58, 0.68, -0.43]]), 1.72, 0.14);
    }
    // 코, 주름(50대)
    add(P(T, [["M", 0.0, 0.12], ["C", -0.07, 0.3, 0.0, 0.38, 0.11, 0.35]]), 1.85, 0.15, { w: 5 });
    add(P(T, [["M", -0.52, 0.38], ["Q", -0.58, 0.55, -0.44, 0.7]]), 1.95, 0.15, { w: 4 });
    add(P(T, [["M", 0.52, 0.38], ["Q", 0.58, 0.55, 0.44, 0.7]]), 1.97, 0.15, { w: 4 });
    add(P(T, [["M", -0.28, -0.62], ["Q", 0, -0.68, 0.28, -0.62]]), 2.0, 0.15, { w: 4 });
    // 입
    if (ex === "sparkle" || ex === "smile") add(P(T, [["M", -0.34, 0.55], ["Q", 0, 0.9, 0.34, 0.55], ["Q", 0, 0.62, -0.34, 0.55], ["Z"]]), 2.05, 0.3, { tint: "pink" });
    else if (ex === "worry" || ex === "sweat" || ex === "sad") add(P(T, [["M", -0.3, 0.74], ["Q", 0, 0.5, 0.3, 0.74]]), 2.05, 0.25);
    else if (ex === "tired") add(P(T, [["M", -0.26, 0.66], ["Q", 0, 0.7, 0.26, 0.62]]), 2.05, 0.25);
    else add(P(T, [["M", -0.26, 0.62], ["L", 0.26, 0.62]]), 2.05, 0.2);
    // 땀방울
    if (ex === "sweat") add(P(T, [["M", 1.05, -0.5], ["C", 1.0, -0.38, 0.88, -0.28, 0.98, -0.18], ["C", 1.12, -0.18, 1.2, -0.38, 1.05, -0.5], ["Z"]]), 2.2, 0.3, { tint: "sky", tintOp: 0.55 });
    return { T, end: s0 + 2.3 * sp };
  }

  // 목+셔츠 몸통. 머리 중심(cx,cy), r. h = 몸 아래 끝(머리 반지름 배수), slump 0..1, 점선 없음
  function torso(c, cx, cy, r, o = {}) {
    const T = (x, y) => [cx + x * r, cy + y * r], sl = o.slump || 0, h = o.h || 4, s0 = o.s || 0, w = o.w || 6, sp = o.sp || 1;
    const sy = 1.95 + sl * 0.55, sx = 2.05 - sl * 0.25, par = o.parent;
    const add = (d, s, dur, x) => c.path(d, Object.assign({ s: s0 + s * sp, dur: dur * sp, w, parent: par }, x || {}));
    const dBody = (k) => { const yy = 1.95 + k * 0.55, xx = 2.05 - k * 0.25; return P(T, [["M", -0.34, 0.98], ["L", -0.34, 1.35], ["C", -1.0, 1.42, -xx + 0.1, 1.5, -xx, yy + 0.3], ["L", -xx - 0.12, h], ["L", xx + 0.12, h], ["L", xx, yy + 0.3], ["C", xx - 0.1, 1.5, 1.0, 1.42, 0.34, 1.35], ["L", 0.34, 0.98]]); };
    c.mask(dBody(sl) + "Z", s0, par);
    const body = add(dBody(sl), 0, 0.8, { tint: "sky" });
    add(P(T, [["M", -0.34, 1.35], ["L", 0, 1.8], ["L", 0.34, 1.35]]), 0.7, 0.3); // V 칼라
    add(P(T, [["M", -0.34, 1.35], ["L", -0.62, 1.5], ["L", -0.3, 1.62]]), 0.85, 0.2, { w: 5 });
    add(P(T, [["M", 0.34, 1.35], ["L", 0.62, 1.5], ["L", 0.3, 1.62]]), 0.88, 0.2, { w: 5 });
    add(P(T, [["M", 0, 1.8], ["L", 0, h]]), 1.0, 0.4, { w: 5 });
    [2.3, 2.8, 3.3].forEach((yy, i) => { if (yy < h - 0.1) add(P(T, [["M", 0.1, yy], ["L", 0.18, yy]]), 1.2 + i * 0.05, 0.08, { w: 6 }); });
    body.morph = (k) => dBody(k);
    return body;
  }
  window.HERO = { face, torso };
})();
