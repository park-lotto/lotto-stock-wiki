"""고유어 수사 읽기(2026-09-16 회원 제보).

제보: 대본에 "10배"라고 쓰면 TTS가 "십 배"라고 읽는다. 그래서 회원이 대본에는
"열배"라고 한글로 쓰고, 6단계 장면꾸미기에서 자막만 "10배"로 고쳐 쓰고 있었다
— 한 편마다 손이 두 번 가는 우회다.

뿌리: normalize_reading이 숫자를 **무조건 한자어**(일·이·삼…)로 읽었다. 한국어는
단위가 무엇이냐에 따라 고유어(열 배·세 개·다섯 명)로 읽어야 한다.

⚠️ 경계가 이 기능의 전부다 — 아래 세 가지를 반드시 지킨다:
  · 100 이상은 고유어를 안 쓴다("백 개"지 "온 개"가 아니다)
  · 단위 뒤에 다른 글자가 붙으면 단위가 아니다("10개월"은 "십 개월", "열 개월" 아님)
  · 한자어 단위(원·분·초·퍼센트…)는 손대지 않는다
"""
from shopping_shorts.narration_naturalize import normalize_reading


def _r(t):
    return normalize_reading(t)[0]


# ---------- 사장님 제보 그 문장 ----------

def test_배는_고유어로_읽는다():
    assert _r("10배") == "열 배"
    assert _r("2배 더") == "두 배 더"
    assert _r("3배나 빨라요") == "세 배나 빨라요"


# ---------- 흔한 고유어 단위 ----------

def test_개_명_살_마리():
    assert _r("5개") == "다섯 개"
    assert _r("1개") == "한 개"          # 하나 → 한(수관형사)
    assert _r("4명") == "네 명"
    assert _r("20살") == "스무 살"        # 스물 → 스무
    assert _r("3마리") == "세 마리"


def test_두자리_고유어():
    assert _r("11개") == "열한 개"
    assert _r("12가지") == "열두 가지"
    assert _r("30분")  != "서른 분"       # 분은 한자어다(아래 별도 검사)
    assert _r("99살") == "아흔아홉 살"


# ---------- 경계 1: 100 이상은 한자어 ----------

def test_백_이상은_한자어로_읽는다():
    assert _r("100개") == "백개"      # 한자어는 종전대로 붙여 쓴다
    assert _r("120명") == "백이십명"


# ---------- 경계 2: 단위 뒤에 글자가 붙으면 단위가 아니다 ----------

def test_개월은_한자어다():
    """'개'로 시작한다고 '열 개월'로 읽으면 안 된다."""
    assert _r("10개월") == "십개월"


def test_조사는_붙어도_고유어를_유지한다():
    assert _r("3개를") == "세 개를"
    assert _r("5명이서") == "다섯 명이서"
    assert _r("2배로") == "두 배로"


# ---------- 경계 3: 한자어 단위는 종전 그대로 ----------

def test_한자어_단위는_그대로():
    assert _r("30분") == "삼십분"
    assert _r("10초") == "십초"
    assert _r("3000원") == "삼천원"


def test_단위없는_숫자는_종전대로_한자어():
    """회귀 방지 — 단위가 없으면 손대지 않는다."""
    assert _r("2026년").startswith("이천")
    assert _r("전화 010") == "전화 십"      # 종전 동작 유지(단위 없음)


def test_기존_단위변환은_그대로():
    """kg·cm 같은 기존 _UNIT_MAP은 한자어 그대로(회귀 방지)."""
    assert _r("3.5kg") == "삼 점 오 킬로그램"
    assert _r("10cm") == "십 센티미터"
