# 채널 정체성 — "훔칠것"을 우리 채널 맥락으로 뽑기 위한 컨텍스트
_CHANNEL = """우리 채널 = "로또의 주식/스탁브레인".
- 타겟 시청자 = 주식에 관심 있는 모든 사람 (시장 흐름을 잘 모르거나 정보를 어떻게
  활용할지 모르는 개인투자자 포함, 초보~중급). AI 관심층 한정 아님.
- 파는 것: 리딩(뭘 사라) 아니라 "나는 시장을 이렇게 본다"는 시각·방법
- 다루는 소재: 오늘 반도체 왜 폭락했나 / 종가·시가 배팅법 / 섹터 흐름 읽기 / 정보 활용법 등
  주식 실전·시황 전반. (AI는 섞을 수 있는 재료일 뿐, 필수 아님)
- 활용 도구는 여러 개: 섹터 히트맵, 주도섹터 강도, 정보정리, 시황 해석, 매매 원칙,
  차트/거래량 해석 등 다양함. '수급빈집'은 그중 하나일 뿐 절대 핵심 아님.
  🚫 '수급빈집'을 제목·핵심에 억지로 넣지 말 것. 이 소재에 정말 딱 맞을 때만, 그것도
  여러 도구 중 하나로만 언급. 기본은 소재 자체(왜 올랐나/어떻게 매매하나 등)로 승부.
- 유튜브 70/20/10 (70 순수정보 / 20 방법노출 / 10 CTA)"""


def _build_q10_prompt(title: str, channel: str, comments: list[dict], stats: dict) -> str:
    """7차원 완전해체 질문 배터리. Gemini가 영상을 본 상태에서 답하도록 구성.
    핵심: '좋다/훌륭하다' 같은 뭉뚱그림 금지, 구체적 메커니즘·문장을 뽑게 강제."""
    cmt_lines = "\n".join(
        f"- (👍{c['like_count']}) {c['text'][:150]}" for c in comments[:15]
    ) or "(댓글 없음/비활성)"
    perf = ""
    if stats:
        perf = (f"이 영상 성과: 조회수 {stats.get('view_count',0):,} / "
                f"채널평균 대비 +{stats.get('view_pct_above_avg',0)}% "
                f"(기여도 {stats.get('contribution_grade','')}) / 구독자 {stats.get('subscriber_count',0):,}")

    return f"""너는 유튜브 콘텐츠 해체 전문가다. 방금 이 영상을 처음부터 끝까지 봤다.
이 영상은 채널 평균 대비 객관적으로 '터진' 검증된 영상이다. 왜 터졌고 뭘 훔쳐올지 완전 해부하라.

영상 제목: {title}
채널: {channel}
{perf}

=== 이 영상의 베스트 댓글 (시청자 실제 반응) ===
{cmt_lines}

=== {_CHANNEL} ===

아래를 JSON으로만 답하라. 각 항목은 '좋다/훌륭하다' 같은 뭉뚱그린 말 절대 금지 —
반드시 구체적 메커니즘·실제 문장·구체 수치를 집어서 답하라:

{{
  "성공요인": "이 영상이 뜬 진짜 이유가 '썸네일/제목'(클릭빨)인지 '대본/스토리'(내용빨)인지 '둘다'인지. 솔직하게 판정",
  "대본_등급": "영상 내용(대본·스토리·전개·설득력)의 완성도 등급 A/B/C + 한줄 이유. 조회수와 무관하게 '내용 자체'만 평가. (썸네일빨이면 C도 가능)",
  "학습가치": "우리가 이 영상에서 배울 게 '썸네일/제목' 위주인지 '대본/구성' 위주인지 한 문장. (썸네일빨이면 '대본 분석 가치 낮음, 썸네일·제목만 참고' 라고 명시)",
  "소재": "이 영상이 판 핵심 주제와 앵글 한 문장 (무엇을 어떤 각도로 다뤘나)",
  "왜_터졌나": "터진 진짜 메커니즘. 제목·타이밍·소재·감정(공포/FOMO/호기심) 중 뭐가 어떻게 작동했나 구체적으로",
  "썸네일": "썸네일에 실제로 보이는 것 — 텍스트 카피(그대로), 인물 표정/시각요소, 그게 노리는 심리 트리거",
  "훅_첫10초": "영상 첫 10~20초 훅을 실제 발화 그대로 인용 + 그 훅이 쓴 기법(질문형/충격수치/모순제기 등)",
  "구성": ["영상을 섹션별로 쪼갠 흐름. 각 항목 '구간명: 하는 것' 형식으로 5~8개"],
  "대본_전체분석": [{{"구간":"00:00~mm:ss", "무슨말":"이 구간에서 실제로 하는 말·주장 요약", "기법":"쓴 화법/설득기법", "핵심대사":"인상적 발화 그대로"}}],
  "내러티브": "전체 스토리 아크 한 문장 (문제제기→긴장→해소를 어떻게 짰나)",
  "대본_훔칠문장": ["우리가 그대로/변형해서 쓸 수 있는 재사용 가능한 문장·전개패턴 3~5개"],
  "댓글_페인포인트": "베스트 댓글이 드러내는, 시청자가 '더 알고 싶어하거나 불만인' 지점 = 이 영상도 못 채운 빈틈 (우리가 채우면 차별화되는 각도)",
  "우리채널_이식": "이 영상의 터진 공식(제목·훅·구성)을 우리 채널 소재로 이식하는 구체적 방법 1~2개. 이 영상 주제에 자연스럽게 맞는 우리 각도로 — 특정 도구(수급빈집 등)를 억지로 끼우지 말 것. 어떤 주식 소재로 어떤 제목·훅으로 바꿀지"
}}"""


def _mix_prompt(cards: list[dict], category: str) -> str:
    """N개 해체카드 → 우리 채널 새 영상 대본 초안 하나로 믹스하는 지시."""
    refs = []
    for i, c in enumerate(cards, 1):
        refs.append(f"""[레퍼런스 {i}] {c.get('_title','')}
- 왜터졌나: {c.get('왜_터졌나','')}
- 훅: {c.get('훅_첫10초','')}
- 구성: {c.get('구성','')}
- 훔칠문장: {c.get('대본_훔칠문장','')}
- 댓글빈틈: {c.get('댓글_페인포인트','')}""")
    refs_txt = "\n\n".join(refs)
    return f"""너는 '로또의 주식' 채널의 대본 작가다. 아래는 '{category}' 카테고리에서 객관적으로 검증된(터진)
레퍼런스 영상 {len(cards)}개를 해체한 결과다. 이것들의 '터진 공식'을 훔쳐서, 우리 채널의
새 영상 대본 하나로 촘촘하게 믹스하라. 단순 짜깁기 금지 — 하나의 탄탄한 스토리로 엮어라.

{refs_txt}

=== {_CHANNEL} ===

요구사항:
1. 여러 레퍼런스의 강점(훅/구성/문장)을 섞되, 하나의 매끄러운 내러티브가 되게.
2. 레퍼런스들이 공통으로 못 채운 '댓글 빈틈'을 우리가 채우는 각도를 반드시 넣어라(차별화).
3. 70/20/10 (70 순수정보 / 20 방법노출 / 10 CTA) 준수.
4. 특정 도구(수급빈집 등)를 억지로 끼우지 말고 소재에 맞는 것만.

JSON으로만 답하라:
{{
  "제목후보": ["끌리는 제목 3개"],
  "훅_첫20초": "실제 발화 대본 (어느 레퍼런스 기법을 썼는지 괄호로 표시)",
  "구성": ["씬별 흐름 6~8개, 각 '구간: 내용 (출처 레퍼런스#)'"],
  "핵심대본_포인트": ["영상에서 꼭 말할 핵심 문장/전개 5개"],
  "차별화_빈틈공략": "레퍼런스들이 못 채운 것을 우리가 어떻게 채우는지",
  "CTA": "마지막 10% CTA 문구",
  "믹스_근거": "어느 레퍼런스에서 무엇을 가져왔는지 요약"
}}"""


def mix(cards: list[dict], category: str = "") -> dict:
    """검증된 해체카드 여러 개 → 우리 채널 새 대본 초안(dict). 제미니가 믹스."""
    raw = G.call(_mix_prompt(cards, category), temperature=0.7)
    draft = G._parse_json_text(raw)
    draft["_refs"] = [{"title": c.get("_title"), "video_id": c.get("_video_id")} for c in cards]
    draft["_category"] = category
    return draft


def teardown(video_id: str, title: str = "", channel: str = "", stats: dict = None) -> dict:
    """영상 1개 완전 해체 → 7차원 카드(dict). Gemini가 영상 시청 + 댓글 종합."""
    comments = hot_clips.get_top_comments(video_id, n=15)
    prompt = _build_q10_prompt(title, channel, comments, stats or {})
    url = f"https://www.youtube.com/watch?v={video_id}"
    raw = G.call_video(url, prompt)
    card = G._parse_json_text(raw)
    # 원본 근거도 카드에 보존 (창고 저장·검증용)
    card["_video_id"] = video_id
    card["_title"] = title
    card["_channel"] = channel
    card["_top_comments"] = comments[:15]
    if stats:
        card["_stats"] = stats
    return card
