_NAME_W = 1  # 채널명(도배 가능) 가중


def _hits(text, kws):
    return sum(1 for kw in kws if kw in text)


def _is_hook_product(name_t, cap_t):
    """제품정체형인가 — 제목 공식 + 문맥어를 함께 본다(단일 키워드 판정 금지).

    '발명품' 한 단어로 판정하면 뉴스·교양 채널이 딸려 온다(라이브 오탐 실측:
    KNN NEWS·지식북·1분홀릭). 그래서 문맥어를 짝으로 요구하고, 교양 신호는 빼낸다.
    0순위-B: 이 판단은 여기 한 곳에서만 한다."""
    blob = f"{name_t} {cap_t}"
    if _hits(blob, _HOOK_BLOCK):
        return False
    if _hits(name_t, _HOOK_NAME):        # 채널명이 이 장르면 제목이 밋밋해도 인정
        return True
    if not _hits(cap_t, KEYWORDS["제품정체형"]):
        return False
    return _hits(cap_t, _HOOK_CONTEXT) >= 2   # 공식의 나머지 반쪽까지 맞아야 통과


def _is_misuse(name_t, cap_t):
    """오용형인가 — 제목 공식 [권위자]도 [부정어] [사용법/활용법] 을 통째로 요구한다.

    단어 하나로 판정하면 안 된다(실측 우려): '개발자'만 보면 IT 브이로그가,
    '사용법'만 보면 사용설명 영상이 전부 딸려 온다. 세 조각이 다 맞아야 인정한다.
      권위자  = 개발자·제조사·판매자·설계자·디자이너 + 브랜드(다이소·이케아·무인양품)
      부정어  = 예상/예측 못한·몰랐던·당황한·몰래 따라한·감탄한
      귀결어  = 사용법·활용법·사용처
    _HOOK_BLOCK(교양·뉴스 차단)은 제품정체형과 공유한다 — 0순위-B, 판단은 한 곳에서.
    """
    # ★차단은 **영상 제목으로만** 판정한다(2026-08-19 실사고).
    #   name_t까지 묶어 검사했더니 '살림치트키'(구독 9,770·정상 쇼핑채널)가 통째로
    #   죽었다 — '치트키'는 지식북 오탐을 막으려고 넣은 말인데 채널명에 그 두 글자가
    #   있다는 이유로 그 채널 영상이 전부 걸러졌다. 교양 여부는 제목이 말해준다.
    if _hits(cap_t, _HOOK_BLOCK):
        return False
    if not _hits(cap_t, _MISUSE_AUTH):
        return False
    if not _hits(cap_t, _MISUSE_NEG):
        return False
    return _hits(cap_t, KEYWORDS["오용형"]) > 0


def _is_gear(name_t, cap_t):
    """장비템인가 — **영상 제목**의 장비 어휘로만 판정한다.

    위 두 특수축과 판정 방식이 다르다. 제품정체형·오용형은 '공식의 조각'을 요구하지만
    장비템은 제품 도메인이 축이라 **장비 어휘 자체**가 신호다. 대신 채널명은 안 본다.

    ★채널명을 신호로 쓰지 않는 이유(2026-08-19 살림치트키 실사고의 반대편):
      채널명 기반 판정은 그 채널 영상을 통째로 물들인다. '공구왕채널'의 잡담 영상까지
      장비템이 되면 안 된다. 장비 여부는 제목이 말해준다.

    ★'집 안 가전'은 홈템에 양보한다 — 로봇청소기·세탁기는 장비가 아니다.
      단 그 말이 제목에 있어도 장비 어휘가 **따로** 있으면 장비템이다
      (예: "에어컨 배관 타공기" — 에어컨은 양보어지만 타공기가 장비다).

    _HOOK_BLOCK(교양·뉴스·게임 차단)은 앞의 두 축과 공유한다 — 0순위-B, 판단은 한 곳.
    """
    if _hits(cap_t, _HOOK_BLOCK):
        return False
    # ★공동구매 글은 장비템이 아니다 — '공구'를 되살린 대가로 반드시 여기서 막는다.
    if _GROUPBUY.search(cap_t):
        return False
    gear = _hits(cap_t, KEYWORDS["장비템"])
    if not gear:
        return False
    # 집 안 가전어만 걸리고 장비 어휘가 그것뿐이면 홈템에 양보한다.
    if gear == 1 and _hits(cap_t, _GEAR_HOME_YIELD):
        for kw in KEYWORDS["장비템"]:
            if kw in cap_t and not any(y in cap_t and kw in y for y in _GEAR_HOME_YIELD):
                return True
        return False
    return True


def _is_car(name_t, cap_t):
    """차량템인가 — **영상 제목**의 차량 제품 어휘로만 판정한다.

    _is_gear와 같은 방식이다(0순위-B: 판정 방식을 두 벌로 만들지 않는다).
    채널명은 안 본다 — 채널명 판정은 그 채널 영상을 통째로 물들인다
    (2026-08-19 '살림치트키' 실사고: 차단어를 채널명에 걸어 정상 채널이 전멸했다).

    ★'차 관련어 개수'로 세지 않는 이유 — 발굴 실측(2026-08-28):
        블박고수(사고영상 컴필) 13/25 · 카진남(운전상식) 13/25  ← 제품을 안 판다
        AnyHome(진짜 판매채널)   8/25                          ← 이게 정답
      개수로 판정했으면 정답이 탈락하고 사고영상이 통과했다.

    _HOOK_BLOCK(교양·뉴스·게임 차단)은 다른 특수축과 공유한다.
    """
    if _hits(cap_t, _HOOK_BLOCK):
        return False
    return _hits(cap_t, KEYWORDS["차량템"]) > 0


def categorize(name, caption=""):
    """채널명+캡션 → topic. 캡션은 전체 키워드(우선 가중), 채널명은 강한 키워드만.
    최고점 채택, 전부 0이면 '기타'."""
    name_t = (name or "").lower()
    cap_t = (caption or "").lower()
    best, best_score = "기타", 0
    for category, kws in KEYWORDS.items():
        if category in ("제품정체형", "오용형", "장비템", "차량템"):
            continue                    # 점수제가 아니라 아래 관문으로 판정한다
        cap_score = _hits(cap_t, kws) * _CAP_W
        name_score = _hits(name_t, NAME_KEYWORDS[category]) * _NAME_W
        score = cap_score + name_score
        if score > best_score:          # 엄격한 > → 동점은 선언 순서(앞선 것) 유지
            best, best_score = category, score
    # ★새 축은 '기타'로 빠지던 것을 건지는 게 목적이라 기본은 기타일 때만 승격한다.
    #   예외: 제목 공식이 뚜렷하면(=후킹형이 확정) 제품어 한 개에 밀리지 않는다.
    #   실측 "다이소도 놀란 한국 천재의 발명품" — '다이소' 한 단어로 홈템에 뺏기던 것.
    #   여기서 지는 쪽은 항상 '약한 단어 1개'이고, 이기는 쪽은 공식 전체다.
    if _is_hook_product(name_t, cap_t) and (best == "기타" or best_score <= _CAP_W):
        return "제품정체형"
    # ★오용형은 제품정체형과 승격 조건이 다르다. 이 장르는 '기타'가 아니라 **홈템**으로
    #   샌다(해시태그에 #살림템·#주방꿀템을 그대로 단다 — 실측 상위 12편 12/12 홈템).
    #   그래서 기타 제한을 걸면 한 건도 못 건진다. 대신 공식 세 조각을 통째로 요구해
    #   (권위자 + 부정어 + 귀결어) 오탐을 막는다 — 판정은 _is_misuse 한 곳에서만.
    if _is_misuse(name_t, cap_t):
        return "오용형"
    # ★장비템은 세 축 중 승격 조건이 또 다르다. 실측(만물상점 21편·쇼핑만물상 3편):
    #   이 장르는 '기타'로 샌다(21/21 기타) — 제품정체형과 같은 쪽이다.
    #   그런데 쇼핑만물상은 해시태그에 #DIY공구·#셀프인테리어를 달아 **홈템으로도** 샌다
    #   ("…센터펀치 꿀팁#센터펀치 #DIY공구 #셀프인테리어" → '셀프인테리어'가 홈템 3점).
    #   그래서 기타 제한만 걸면 쇼핑만물상 결이 통째로 빠진다 → 오용형처럼 공식이 이기게 한다.
    #   대신 지는 쪽이 '약한 단어 몇 개'일 때만 이기도록 점수 상한을 둔다(홈템 본진은 안 뺏는다).
    # ★차량템을 장비템보다 **먼저** 본다. 둘 다 걸리는 제목("차박 매트")은
    #   차량템이 더 구체적이라 그쪽이 맞다 — 장비템은 집 밖 현장이 본진이다.
    if _is_car(name_t, cap_t) and best_score <= _CAR_CAP:
        return "차량템"
    if _is_gear(name_t, cap_t) and best_score <= _GEAR_CAP:
        return "장비템"
    return best


def ctype_of(topic):
    """topic → 유형(비법형/제품형/혼합형/기타)."""
    return TOPIC_CTYPE.get(topic, "기타")


def classify(name, caption=""):
    """topic·ctype 동시 반환: {'topic':..., 'ctype':...}."""
    topic = categorize(name, caption)
    return {"topic": topic, "ctype": ctype_of(topic)}


