"""채널명+캡션 키워드 기반 카테고리 자동 태깅.

두 축을 태깅한다.
- topic(세부주제): 인테리어/레시피/생활용품/가전/뷰티/기타
- ctype(유형): 비법형/제품형/혼합형  ← 제작·수익화 방식(초보자 탐색축)
    비법형 = 특정 제품이 아니라 CTA에서 비법소스·비법가루·액체 등 '숨긴 것'을 공개 (인테리어·레시피)
    제품형 = 정확한 특정 제품을 설명·추천 (생활용품·가전) → 소스매칭 대상
    혼합형 = 제품 소개와 비법이 섞임 (뷰티)

분류 로직(과거 '첫 매칭 승리'의 오분류를 개선):
- A. 캡션 우선: 채널명보다 그 영상의 캡션 키워드를 더 크게 가중(_CAP_W).
      채널명에 태그를 도배한 채널(예: "집꾸미기|인테리어|살림템")이 올린
      요리 영상이 인테리어로 빠지던 문제를 잡는다.
- B. 최다득표: 첫 매칭이 아니라 카테고리별 매칭 점수를 합산해 최고점 채택.
- C. 키워드 보강: 음식·가전·수납 등 실제 등장어를 폭넓게 포함.
동점이면 KEYWORDS 선언 순서(앞선 것) 우선. 전부 0점이면 '기타'.
(D. AI 비전 판별은 애매 케이스용 후속 단계 — 여기선 텍스트만 사용.)
"""

# 선언 순서 = 동점 시 우선순위.
KEYWORDS = {
    "인테리어": ["인테리어", "diy", "셀프", "홈스타일", "집꾸", "공간", "홈데코",
              "홈스타일링", "수납", "집들이", "셀프인테리어"],
    "레시피": ["레시피", "요리", "맛집", "자취요리", "쿠킹", "베이킹",
             "감자", "오이", "계란", "달걀", "김치", "반찬", "간식", "디저트",
             "소스", "양념", "찌개", "볶음", "조림", "무침", "절임", "국물", "밑반찬"],
    "생활용품": ["살림", "생활용품", "꿀템", "주방", "정리", "청소템", "살림템",
              "정리템", "수납템", "다이소", "생필품", "만능템"],
    "가전": ["가전", "로봇청소기", "청소기", "에어컨", "냉장고", "언박싱",
            "에어프라이어", "전자레인지", "세탁기", "건조기", "가습기", "선풍기",
            "밥솥", "믹서기"],
    "뷰티": ["뷰티", "화장", "메이크업", "스킨케어", "코스메틱", "화장품",
            "쿠션", "세럼", "클렌징", "향수", "네일"],
}

# topic → 유형(ctype) 매핑. 초보자 탐색축(제작·수익화 방식).
TOPIC_CTYPE = {
    "인테리어": "비법형",
    "레시피": "비법형",
    "생활용품": "제품형",
    "가전": "제품형",
    "뷰티": "혼합형",
    "기타": "기타",
}

_CAP_W = 3   # 캡션(영상별 신호) 가중
_NAME_W = 1  # 채널명(도배 가능) 가중


def _hits(text, kws):
    return sum(1 for kw in kws if kw in text)


def categorize(name, caption=""):
    """채널명+캡션 → topic. 캡션 우선 가중 점수제, 최고점 채택. 없으면 '기타'."""
    name_t = (name or "").lower()
    cap_t = (caption or "").lower()
    best, best_score = "기타", 0
    for category, kws in KEYWORDS.items():
        score = _hits(cap_t, kws) * _CAP_W + _hits(name_t, kws) * _NAME_W
        if score > best_score:          # 엄격한 > → 동점은 선언 순서(앞선 것) 유지
            best, best_score = category, score
    return best


def ctype_of(topic):
    """topic → 유형(비법형/제품형/혼합형/기타)."""
    return TOPIC_CTYPE.get(topic, "기타")


def classify(name, caption=""):
    """topic·ctype 동시 반환: {'topic':..., 'ctype':...}."""
    topic = categorize(name, caption)
    return {"topic": topic, "ctype": ctype_of(topic)}
